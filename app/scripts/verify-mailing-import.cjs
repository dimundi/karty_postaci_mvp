const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const express = require('express')
const { chromium } = require('playwright-core')
const { installMailingList, normalizeEmail, validateList } = require('./mailing-list-server.cjs')
const { parseCsv, prepareImport, nextSequence } = require('./mailing-import-server.cjs')

async function verify() {
  const csv = 'order,name,email\r\nA,"Pole, z przecinkiem",FIRST@Example.com\r\nB,"Pole ""cytowane""",second@example.com\r\n'
  const bytes = Buffer.concat([Buffer.from([0xff, 0xfe]), Buffer.from(csv, 'utf16le')])
  const records = parseCsv(bytes)
  assert.equal(records.length, 2)
  assert.equal(parseCsv(Buffer.from('order,email\nA,a@example.com')).length, 1)
  assert.throws(() => parseCsv(Buffer.from('order,email\nA,"a@example.com')))
  assert.throws(() => parseCsv(Buffer.from('order,email\nA,"a@example.com"garbage')))
  assert.throws(() => parseCsv(Buffer.from('order,email,email\nA,a@example.com,b@example.com')))
  const initial = { schemaVersion: 1, recipients: [900, 901].map((sequenceNumber) => ({ id: `test-${sequenceNumber}`, email: `test${sequenceNumber}@example.com`, sequenceNumber, orderId: 'TEST', createdAt: new Date().toISOString(), deliveryStatus: 'not_sent', talentId: null })) }
  validateList(initial)
  assert.equal(prepareImport(records, initial, normalizeEmail).rows[0].sequenceNumber, 1)
  const nearTestNumbers = { recipients: [...initial.recipients, { orderId: 'Z', sequenceNumber: 899 }] }
  assert.equal(nextSequence(nearTestNumbers)(), 902)
  assert.throws(() => validateList({ ...initial, recipients: initial.recipients.map((r) => ({ ...r, sequenceNumber: 900 })) }))
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'klanarchia-import-'))
  const file = path.join(directory, 'mailing-list.json')
  fs.writeFileSync(file, JSON.stringify(initial))
  const app = express(); installMailingList(app, file)
  const server = await new Promise((resolve) => { const s = app.listen(0, '127.0.0.1', () => resolve(s)); })
  const base = `http://127.0.0.1:${server.address().port}/api/mailing-list`
  const post = (route, value) => fetch(base + route, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(value) })
  const preview = (body) => fetch(base + '/import-preview', { method: 'POST', body })
  let browser
  try {
    const before = fs.readFileSync(file, 'utf8')
    const draft = await (await preview(bytes)).json()
    assert.equal(draft.added, 2); assert.equal(draft.errors, 0)
    assert.equal(fs.readFileSync(file, 'utf8'), before)
    const imported = await (await post('/import', { draftId: draft.draftId })).json()
    assert.equal(imported.list.recipients.length, 4)
    assert.deepEqual(imported.list.recipients.map((r) => r.sequenceNumber), [900, 901, 1, 2])
    assert.ok(fs.existsSync(file + '.bak'))
    const repeated = await (await preview(bytes)).json()
    assert.equal(repeated.added, 0); assert.equal(repeated.skipped, 2)
    const conflicts = await (await preview(Buffer.from('order,email\nA,other@example.com\nC,first@example.com'))).json()
    assert.equal(conflicts.errors, 2)
    assert.equal((await post('/import', { draftId: conflicts.draftId })).status, 400)
    const sameFile = await (await preview(Buffer.from('order,email\nD,d@example.com\nD,d@example.com'))).json()
    assert.equal(sameFile.added, 1); assert.equal(sameFile.skipped, 1)
    const testException = await (await preview(Buffer.from('order,email\nTEST,test2@example.com\nTEST,test3@example.com'))).json()
    assert.equal(testException.errors, 0)
    const first = imported.list.recipients.find((r) => r.orderId === 'A')
    assert.equal((await post('/edit', { id: first.id, originalEmail: first.email, email: 'second@example.com' })).status, 400)
    const edited = await (await post('/edit', { id: first.id, originalEmail: first.email, email: 'CHANGED@Example.com' })).json()
    assert.deepEqual(edited.recipients.find((r) => r.id === first.id), { ...first, email: 'changed@example.com' })
    assert.equal((await post('/edit', { id: first.id, originalEmail: first.email, email: 'again@example.com' })).status, 409)
    assert.equal((await post('/import', { draftId: sameFile.draftId })).status, 409)
    // Osobna lista tymczasowa i przekierowanie API: test UI nie dotyka prywatnej listy.
    fs.writeFileSync(file, JSON.stringify(initial))
    browser = await chromium.launch({ executablePath: '/usr/bin/chromium', args: ['--no-sandbox', '--disable-dev-shm-usage'] })
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
    const errors = []; page.on('pageerror', (error) => errors.push(error.message))
    await page.route('**/api/mailing-list**', async (route) => {
      const request = route.request(), url = new URL(request.url())
      const response = await route.fetch({ url: base.replace('/api/mailing-list', '') + url.pathname + url.search })
      await route.fulfill({ response })
    })
    await page.goto('http://localhost:8080/#dev-mailing-list')
    await page.getByRole('cell', { name: 'test900@example.com', exact: true }).waitFor()
    const chooserEvent = page.waitForEvent('filechooser')
    await page.getByRole('button', { name: 'Przeglądaj', exact: true }).click()
    await (await chooserEvent).setFiles({ name: 'sample.csv', mimeType: 'text/csv', buffer: bytes })
    await page.getByText('Wybrany plik: sample.csv', { exact: true }).waitFor()
    await page.getByRole('button', { name: 'Pokaż podgląd importu' }).click()
    await page.getByRole('heading', { name: 'Podgląd importu', exact: true }).waitFor()
    assert.equal(JSON.parse(fs.readFileSync(file)).recipients.length, 2)
    await page.getByRole('button', { name: 'Zatwierdź import', exact: true }).click()
    await page.getByRole('status').filter({ hasText: 'Import zakończony.' }).waitFor()
    await page.getByRole('button', { name: 'Edytuj first@example.com', exact: true }).click()
    await page.getByLabel('Nowy adres e-mail', { exact: true }).fill('edited@example.com')
    await page.getByRole('button', { name: 'Zapisz adres', exact: true }).click()
    await page.getByRole('cell', { name: 'edited@example.com', exact: true }).waitFor()
    await page.reload()
    await page.getByRole('cell', { name: 'edited@example.com', exact: true }).waitFor()
    const persisted = JSON.parse(fs.readFileSync(file)).recipients.find((r) => r.orderId === 'A')
    assert.equal(persisted.sequenceNumber, 1)
    assert.equal(persisted.email, 'edited@example.com')
    await page.setViewportSize({ width: 390, height: 844 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    assert.deepEqual(errors, [])
    console.log('OK: parser CSV UTF-16/UTF-8, walidacja, numeracja, wyjątek TEST, duplikaty, konflikty, nieaktualny podgląd, atomowy zapis; UI wyboru/podglądu/importu/edycji i odświeżenie. Wyłącznie dane tymczasowe.')
  } finally {
    if (browser) await browser.close()
    await new Promise((resolve) => server.close(resolve))
    fs.rmSync(directory, { recursive: true, force: true })
  }
}
verify().catch((error) => { console.error(error); process.exitCode = 1 })
