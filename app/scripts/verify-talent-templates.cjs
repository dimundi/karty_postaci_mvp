const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const os = require('node:os')
const { execFileSync } = require('node:child_process')
const express = require('express')
const { chromium } = require('playwright-core')
const { PDFDocument } = require('pdf-lib')
const { defaultTemplate, renderTemplate, ASSETS, polishText, fitText } = require('../src/talentTemplates/template.cjs')
const { installTalentTemplates, validateTemplate } = require('./talent-templates-server.cjs')
const { installTalents, planImport, validateLibrary } = require('./talents-server.cjs')
async function verify() {
  execFileSync(process.execPath, ['node_modules/typescript/bin/tsc', '--noEmit'], { stdio: 'inherit' })
  const template = defaultTemplate()
  assert.equal(polishText('w i z domu'), 'w\u00a0i\u00a0z\u00a0domu')
  const polish = polishText('przekonywania ciemności')
  assert.ok(polish.includes('\u00ad'))
  assert.equal(polish.replace(/\u00ad/g, ''), 'przekonywania ciemności')
  assert.ok(polishText('<>&').includes('&lt;&gt;&amp;'))
  validateTemplate(template)
  assert.throws(() => validateTemplate({ ...template, schemaVersion: 1 }), /format/)
  assert.throws(() => validateTemplate({ ...template, page: { width: 400, height: 200 } }), /format/)
  const sample = { id: 'example', name: 'Próba żółci', flavorDescription: 'Opis fabularny.', description: 'Opis działania z polskimi znakami.', usesPerMission: 3, group: 'Inna grupa', subgroup: null, code: null, isDarkGift: true }
  for (const uses of [0, 1, 2, 3]) for (const dark of [true, false]) {
    const html = renderTemplate(template, { ...sample, usesPerMission: uses, isDarkGift: dark })
    assert.equal((html.match(/data-use-square/g) || []).length, uses)
    assert.equal(/<img\b[^>]*data-part="darkGift"/.test(html), dark)
    assert.equal((html.match(/data-text=/g) || []).length, 1)
    assert.ok(html.includes('data-part="hex"'))
  }
  assert.ok(renderTemplate(template, { ...sample, name: '<script>bad</script>' }).includes('&lt;script&gt;'))
  assert.equal(validateLibrary({ schemaVersion: 1, talents: [{ ...sample, isDarkGift: undefined, group: 'Dary Ciemności' }] }).talents[0].isDarkGift, false)
  assert.equal(planImport({ talents: [sample] }, [{ ...sample, isDarkGift: false }])[0].talent.isDarkGift, true)
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'talent-html-'))
  const file = path.join(directory, 'szablon.json'), talentsFile = path.join(directory, 'talenty.json')
  fs.writeFileSync(talentsFile, JSON.stringify({ schemaVersion: 1, talents: [sample] }))
  const original = fs.readFileSync(talentsFile, 'utf8')
  const app = express()
  installTalents(app, talentsFile)
  installTalentTemplates(app, { file, assetsDirectory: '/cardTemplates/talenty/Links' })
  const server = await new Promise((resolve) => { const s = app.listen(0, '127.0.0.1', () => resolve(s)) })
  const base = `http://127.0.0.1:${server.address().port}`
  const post = (url, data) => fetch(base + url, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(data) })
  let browser, page
  try {
    for (const asset of Object.values(ASSETS)) assert.equal((await fetch(base + '/api/talent-asset?file=' + encodeURIComponent(asset))).status, 200)
    assert.equal((await fetch(base + '/api/talent-asset?file=../talenty.json')).status, 400)
    assert.equal((await post('/api/talent-template', { template, revision: null })).status, 200)
    assert.equal((await post('/api/talent-template', { template, revision: null })).status, 409)
    const pdfResponse = await post('/api/talent-template-pdf', { template, preview: sample })
    assert.equal(pdfResponse.status, 200)
    const pdf = await PDFDocument.load(await pdfResponse.arrayBuffer())
    assert.equal(pdf.getPageCount(), 1)
    assert.ok(Math.abs(pdf.getPage(0).getWidth() - template.page.width) < .5)
    assert.ok(Math.abs(pdf.getPage(0).getHeight() - template.page.height) < .5)
    const overflow = await post('/api/talent-template-pdf', { template: { ...template, autoFit: false, fontSize: 20 }, preview: { ...sample, description: 'Długi opis. '.repeat(500) } })
    assert.equal(overflow.status, 400)
    browser = await chromium.launch({ executablePath: '/usr/bin/chromium', args: ['--no-sandbox', '--disable-dev-shm-usage'] })
    page = await browser.newPage({ viewport: { width: 1600, height: 1000 } })
    const errors = []; page.on('pageerror', (e) => errors.push(e.message))
    await page.route('**/api/talent**', async (route) => { const url = new URL(route.request().url()); const response = await route.fetch({ url: base + url.pathname + url.search }); await route.fulfill({ response }) })
    await page.goto('http://localhost:8080/#dev-talent-templates')
    await page.getByLabel('Wczytaj dane talentu', { exact: true }).waitFor()
    const card = page.frameLocator('iframe')
    await card.locator('[data-part="darkGift"]').waitFor()
    assert.equal(await card.locator('[data-use-square]').count(), 3)
    assert.equal(await card.locator('[data-text]').count(), 1)
    const statusBox = await card.locator('[data-part="status"]').boundingBox(), textBox = await card.locator('[data-part="text"]').boundingBox()
    assert.ok(textBox.y >= statusBox.y + statusBox.height)
    const hex = await card.locator('[data-part="hex"]').boundingBox(), dark = await card.locator('[data-part="darkGift"]').boundingBox(), square = await card.locator('[data-use-square]').first().boundingBox()
    assert.ok(dark.x > hex.x && square.x > dark.x)
    assert.ok(dark.height > hex.height * 1.3)
    await page.getByLabel('Dar Ciemności', { exact: true }).uncheck()
    await card.locator('[data-part="darkGift"]').waitFor({ state: 'detached' })
    await page.getByLabel('Liczba użyć na misję', { exact: true }).selectOption('0')
    await card.locator('[data-use-square]').waitFor({ state: 'detached' })
    await page.getByLabel('Dar Ciemności', { exact: true }).check()
    await page.getByLabel('Liczba użyć na misję', { exact: true }).selectOption('2')
    await page.getByLabel('Nazwa talentu', { exact: true }).fill('Wyłącznie podgląd')
    await page.getByLabel('Rozmiar tekstu (pt)', { exact: true }).fill('8')
    await page.getByRole('button', { name: 'Zapisz szablon', exact: true }).click()
    await page.getByRole('status').filter({ hasText: 'Zapisano wspólny' }).waitFor()
    assert.equal(fs.readFileSync(talentsFile, 'utf8'), original)
    assert.equal(JSON.parse(fs.readFileSync(file)).fontSize, 8)
    assert.equal(await page.getByRole('button', { name: 'Dodaj pole', exact: true }).count(), 0)
    await page.getByLabel('Wskaż wybrany element', { exact: true }).uncheck()
    const downloadEvent = page.waitForEvent('download')
    await page.getByRole('button', { name: 'Pobierz próbny PDF', exact: true }).click()
    await (await downloadEvent).saveAs('/app/.cache/talent-template-test.pdf')
    const imageDownload = page.waitForEvent('download')
    await page.getByRole('button', { name: 'Pobierz grafikę na Facebooka', exact: true }).click()
    await (await imageDownload).saveAs('/app/.cache/talent-facebook-test.png')
    const png = fs.readFileSync('/app/.cache/talent-facebook-test.png')
    assert.equal(png.subarray(0, 8).toString('hex'), '89504e470d0a1a0a')
    assert.equal(png.readUInt32BE(16), 1200)
    assert.equal(png.readUInt32BE(20), 1200)
    assert.equal(fs.readFileSync(talentsFile, 'utf8'), original)
    await page.screenshot({ path: '/app/.cache/talent-template-desktop.png', fullPage: true })
    await page.reload(); await page.getByLabel('Rozmiar tekstu (pt)', { exact: true }).waitFor()
    assert.equal(await page.getByLabel('Rozmiar tekstu (pt)', { exact: true }).inputValue(), '8')
    await page.setViewportSize({ width: 390, height: 844 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true)
    await page.screenshot({ path: '/app/.cache/talent-template-mobile.png', fullPage: true })
    const checkPage = await browser.newPage()
    const source = JSON.parse(fs.readFileSync('/cardTemplates/talenty/talenty.json', 'utf8'))
    const images = Object.fromEntries(Object.entries(ASSETS).map(([key, name]) => [key, `${base}/api/talent-asset?file=${encodeURIComponent(name)}`]))
    for (const talent of source.talents) {
      await checkPage.setContent(renderTemplate(defaultTemplate(), talent, { images }), { waitUntil: 'load' })
      await checkPage.evaluate(() => document.fonts.ready)
      assert.deepEqual(await checkPage.evaluate(fitText), [], `Tekst nie mieści się: ${talent.name}`)
    }
    await checkPage.close()
    await page.goto('http://localhost:8080/#dev-talents')
    await page.getByLabel('Dar Ciemności — pokaż ikonę', { exact: true }).waitFor()
    await page.getByLabel('Dar Ciemności — pokaż ikonę', { exact: true }).uncheck()
    await page.getByRole('button', { name: 'Zapisz talent', exact: true }).click()
    await page.getByRole('status').filter({ hasText: 'Zapisano talent.' }).waitFor()
    assert.equal(JSON.parse(fs.readFileSync(talentsFile)).talents[0].isDarkGift, false)
    assert.equal(JSON.parse(fs.readFileSync(talentsFile)).talents[0].group, 'Inna grupa')
    assert.deepEqual(errors, [])
    console.log('OK: TypeScript, jeden szablon, SVG, stały pasek statusu i płynny blok tekstu, flagi niezależne od grupy, 0–3 użycia, import zachowuje flagę, zapis ustawień, podgląd bez zapisu danych, PDF i przepełnienie, telefon. Test na osobnych danych.')
  } catch (error) { if (page) await page.screenshot({ path: '/app/.cache/talent-template-error.png', fullPage: true }).catch(() => {}); throw error }
  finally { if (browser) await browser.close(); await new Promise((resolve) => server.close(resolve)); fs.rmSync(directory, { recursive: true, force: true }) }
}
verify().catch((error) => { console.error(error); process.exitCode = 1 })
