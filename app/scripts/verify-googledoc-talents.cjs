const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const XLSX = require('xlsx')
const express = require('express')
const { chromium } = require('playwright-core')
const { parseGoogleDocWorkbook } = require('./talent-googledoc-import.cjs')
const { installTalents, validateTalent, planImport } = require('./talents-server.cjs')

function workbook(rows) {
  const book = XLSX.utils.book_new()
  const sheet = XLSX.utils.aoa_to_sheet([[], ['Kolumna nr 1', 'Nazwa', 'Akcja', 'Opis fabularny', 'Opis mechaniczny', 'Użycia', 'Typ'], ...rows])
  sheet['!ref'] = 'A1:AA1001'
  XLSX.utils.book_append_sheet(book, sheet, 'Arkusz1')
  XLSX.utils.book_append_sheet(book, XLSX.utils.aoa_to_sheet([['Pomijany wpis', 'Brak użyć']]), 'Arkusz2')
  return XLSX.write(book, { type: 'buffer', bookType: 'xlsx' })
}
async function verify() {
  const bytes = workbook([['', 'Jeden', 'akcja', 'Fabularny', '**Opis**.', 1, 'Meta'], ['', 'Dwa', '', '', 'Opis drugi.', 0, 'Mutacja']])
  const parsed = parseGoogleDocWorkbook(bytes, 'Dary', 'Nowa', true, validateTalent)
  assert.equal(parsed.talents.length, 2)
  assert.deepEqual(parsed.ignoredSheets, ['Arkusz2'])
  assert.equal(parsed.talents[0].dev_type, 'Meta')
  assert.equal(parsed.talents[0].subgroup, 'Nowa')
  assert.equal(parsed.talents[0].isAction, true)
  assert.equal(parsed.talents[1].isAction, false)
  const extraColumns = XLSX.read(bytes, { type: 'buffer' })
  extraColumns.Sheets.Arkusz1.H2 = { t: 's', v: 'Pomijana kolumna' }
  extraColumns.Sheets.Arkusz1.H3 = { t: 'n', v: 2, f: '1+1' }
  assert.deepEqual(parseGoogleDocWorkbook(XLSX.write(extraColumns, { type: 'buffer', bookType: 'xlsx' }), 'Dary', 'Nowa', true, validateTalent), parsed)
  const sceneTalent = parseGoogleDocWorkbook(workbook([['', 'Jeden', '', '', 'Opis.', '1/scenę', 'Meta']]), 'Dary', 'Nowa', true, validateTalent).talents[0]
  assert.equal(sceneTalent.oncePerScene, true)
  assert.equal(sceneTalent.usesPerMission, 0)
  assert.equal(parsed.talents[0].oncePerScene, false)
  const sceneLibrary = { schemaVersion: 1, talents: [{ ...parsed.talents[0], id: 'scene-existing' }] }
  assert.equal(planImport(sceneLibrary, [sceneTalent], { source: 'googledoc' })[0].talent.oncePerScene, true)
  assert.equal(planImport({ ...sceneLibrary, talents: [{ ...sceneTalent, id: 'scene-existing' }] }, [parsed.talents[0]], { source: 'googledoc' })[0].talent.oncePerScene, false)
  assert.throws(() => parseGoogleDocWorkbook(bytes, 'Dary', '', true, validateTalent), /podgrupę/)
  assert.throws(() => parseGoogleDocWorkbook(workbook([['', 'Błąd', '', '', 'Opis', '', 'Meta']]), 'Dary', 'Nowa', true, validateTalent), /wiersz 3/)
  const initial = { schemaVersion: 1, talents: [
    { ...parsed.talents[0], id: 'existing', isDarkGift: false, isAction: false, dev_type: 'Mutacja', code: 'A7K2-M9B4' },
    { ...parsed.talents[0], id: 'outside', name: 'Poza importem', subgroup: 'Ogólne', isDarkGift: false },
  ] }
  const preserved = planImport(initial, parsed.talents, { source: 'googledoc', isDarkGift: true })
  assert.equal(preserved[0].talent.isDarkGift, false)
  assert.equal(preserved[0].talent.dev_type, 'Meta')
  assert.equal(preserved[0].talent.isAction, true)
  assert.equal(preserved[0].talent.id, 'existing')
  assert.equal(preserved[0].talent.code, 'A7K2-M9B4')
  assert.equal(preserved[1].talent.isDarkGift, true)
  assert.equal(planImport(initial, parsed.talents, { source: 'googledoc', isDarkGift: true, overrideDarkGift: true })[0].talent.isDarkGift, true)
  assert.equal(planImport(initial, parsed.talents, { source: 'googledoc', isDarkGift: false, overrideDarkGift: true })[0].talent.isDarkGift, false)
  assert.equal(planImport(initial, [{ ...parsed.talents[0], dev_type: null }])[0].talent.dev_type, 'Mutacja')
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'googledoc-talents-'))
  const file = path.join(directory, 'talents.json')
  fs.writeFileSync(file, JSON.stringify(initial))
  const app = express(); installTalents(app, file)
  const server = await new Promise((resolve) => { const s = app.listen(0, '127.0.0.1', () => resolve(s)); })
  const base = `http://127.0.0.1:${server.address().port}`
  let browser
  try {
    const before = fs.readFileSync(file, 'utf8')
    const params = new URLSearchParams({ source: 'googledoc', group: 'Dary', subgroup: 'Nowa', isDarkGift: 'true', overrideDarkGift: 'true' })
    const response = await fetch(`${base}/api/talents/import-preview?${params}`, { method: 'POST', body: bytes })
    const preview = await response.json()
    assert.equal(response.status, 200, preview.error)
    assert.equal(fs.readFileSync(file, 'utf8'), before)
    browser = await chromium.launch({ executablePath: '/usr/bin/chromium', args: ['--no-sandbox', '--disable-dev-shm-usage'] })
    const page = await browser.newPage()
    const errors = []; page.on('pageerror', (e) => errors.push(e.message))
    await page.route('**/api/talents**', async (route) => {
      const url = new URL(route.request().url())
      const response = await route.fetch({ url: base + url.pathname + url.search })
      await route.fulfill({ response })
    })
    await page.goto('http://localhost:8080/#dev-talents')
    await page.getByLabel('dev_type — Typ', { exact: true }).selectOption('Kontrakt')
    await page.getByRole('button', { name: 'Zapisz talent', exact: true }).click()
    await page.getByRole('status').filter({ hasText: 'Zapisano talent.' }).waitFor()
    assert.equal(JSON.parse(fs.readFileSync(file)).talents[0].dev_type, 'Kontrakt')
    await page.getByRole('button', { name: 'Importuj XLS / XLSX', exact: true }).click()
    await page.getByLabel('Procedura importu', { exact: true }).selectOption('googledoc')
    await page.getByLabel('Grupa importowanych talentów', { exact: true }).fill('Dary')
    await page.getByLabel('Podgrupa dla importu', { exact: true }).fill('Nowa')
    await page.getByLabel('Plik XLS lub XLSX').setInputFiles({ name: 'test.xlsx', mimeType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', buffer: bytes })
    await page.getByRole('checkbox', { name: 'isDarkGift — Dar Ciemności dla importu', exact: true }).check()
    await page.getByRole('checkbox', { name: 'Nadpisz isDarkGift dla wszystkich importowanych talentów', exact: true }).check()
    const beforePreview = fs.readFileSync(file, 'utf8')
    await page.getByRole('button', { name: 'Pokaż podgląd importu', exact: true }).click()
    await page.getByRole('heading', { name: 'Podgląd importu', exact: true }).waitFor()
    await page.getByText('Pominięte arkusze: Arkusz2.', { exact: true }).waitFor()
    assert.equal(fs.readFileSync(file, 'utf8'), beforePreview)
    assert.equal(await page.locator('.talent-import-item').count(), 2)
    assert.equal(await page.locator('.talent-import-preview details').count(), 0)
    await page.setViewportSize({ width: 390, height: 500 })
    const workspace = page.locator('main.talent-workspace')
    await workspace.evaluate((node) => { node.scrollTop = 0 })
    await workspace.hover({ position: { x: 10, y: 250 } })
    await page.mouse.wheel(0, 600)
    await page.waitForFunction(() => document.querySelector('main.talent-workspace').scrollTop > 0)
    await page.locator('.talent-import-item').last().scrollIntoViewIfNeeded()
    await page.locator('.talent-import-item').last().getByText('Opis drugi.', { exact: true }).waitFor()
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await page.setViewportSize({ width: 1280, height: 720 })
    await page.getByRole('checkbox', { name: 'isDarkGift — Dar Ciemności dla importu', exact: true }).uncheck()
    assert.equal(await page.getByRole('heading', { name: 'Podgląd importu', exact: true }).count(), 0)
    await page.getByRole('checkbox', { name: 'isDarkGift — Dar Ciemności dla importu', exact: true }).check()
    await page.getByRole('button', { name: 'Pokaż podgląd importu', exact: true }).click()
    await page.getByRole('heading', { name: 'Podgląd importu', exact: true }).waitFor()
    await page.getByRole('button', { name: 'Zatwierdź import', exact: true }).click()
    await page.getByRole('status').filter({ hasText: 'Import zakończony' }).waitFor()
    const saved = JSON.parse(fs.readFileSync(file))
    assert.equal(saved.talents.length, 3)
    assert.ok(saved.talents.filter((t) => t.subgroup === 'Nowa').every((t) => t.isDarkGift))
    assert.deepEqual(saved.talents.find((t) => t.id === 'outside'), initial.talents[1])
    assert.equal(saved.talents.find((t) => t.id === 'existing').dev_type, 'Meta')
    assert.deepEqual(errors, [])
    console.log('OK: GoogleDoc, dev_type, isAction, osobna podgrupa, zachowanie ID/kodu, opcjonalne nadpisanie isDarkGift, podgląd bez zapisu, import i edycja przez UI. Wyłącznie dane tymczasowe.')
  } finally {
    if (browser) await browser.close()
    await new Promise((resolve) => server.close(resolve))
    fs.rmSync(directory, { recursive: true, force: true })
  }
}
verify().catch((e) => { console.error(e); process.exitCode = 1 })
