const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const { chromium } = require('playwright-core')
const { PDFDocument } = require('pdf-lib')
const { validateProject, fieldsConfig, PAGE } = require('./card-creator-server.cjs')

async function verify() {
  const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', args: ['--no-sandbox', '--disable-dev-shm-usage'] })
  const name = `Test Żółć ${Date.now()}`
  const directory = path.join('/cardTemplates/projekty', name)
  let created = false
  try {
    const page = await browser.newPage({ viewport: { width: 1600, height: 1100 } })
    const errors = []
    page.on('pageerror', (error) => errors.push(error.message))
    await page.goto('http://localhost:8080/#dev-clans')
    await page.getByRole('heading', { name: 'Kreator szablonów', exact: true }).waitFor()
    await page.getByRole('button', { name: 'Obraz', exact: true }).waitFor()
    await page.getByLabel('Powiększenie').selectOption('2')
    const workspace = page.locator('.creator-page-scroll')
    const viewport = await workspace.boundingBox()
    const cursor = { x: viewport.x + viewport.width / 2, y: viewport.y + viewport.height / 2 }
    await page.mouse.move(cursor.x, cursor.y)
    await page.mouse.wheel(0, 120)
    await page.waitForFunction(() => document.querySelector('.creator-page-scroll').scrollTop > 0)
    await page.evaluate(() => new Promise((resolve) => {
      const workspace = document.querySelector('.creator-page-scroll')
      let previous = workspace.scrollTop, stable = 0
      function frame() {
        stable = workspace.scrollTop === previous ? stable + 1 : 0
        previous = workspace.scrollTop
        if (stable >= 12) resolve()
        else requestAnimationFrame(frame)
      }
      requestAnimationFrame(frame)
    }))
    assert.equal(await page.getByLabel('Powiększenie').inputValue(), '2')
    const beforeZoom = await page.locator('.creator-page').boundingBox()
    await page.keyboard.down('Control')
    await page.mouse.wheel(0, -120)
    await page.keyboard.up('Control')
    await page.waitForFunction(() => Number(document.querySelector('.creator-zoom-controls select').value) > 2)
    const afterZoom = await page.locator('.creator-page').boundingBox()
    const anchorBefore = (cursor.y - beforeZoom.y) / beforeZoom.height
    const anchorAfter = (cursor.y - afterZoom.y) / afterZoom.height
    assert.ok(Math.abs(anchorBefore - anchorAfter) < .005, `Punkt pod kursorem: ${anchorBefore} → ${anchorAfter}`)
    await page.getByRole('button', { name: 'Oddal kartę' }).click()
    await page.getByLabel('Powiększenie').selectOption('page')
    await page.getByRole('button', { name: 'Menu kreatora' }).click()
    assert.equal(await page.getByRole('menuitem', { name: 'Utwórz wariant' }).isDisabled(), true)
    await page.getByRole('menuitem', { name: 'Utwórz projekt', exact: true }).click()
    await page.getByLabel('Nazwa projektu', { exact: true }).fill('Test Żółć')
    await page.getByLabel('Identyfikator projektu').fill('test')
    await page.getByRole('button', { name: 'Zamknij metrykę' }).click()
    const surface = page.locator('.creator-page')
    await page.getByRole('button', { name: 'Obraz', exact: true }).click()
    await page.getByRole('button', { name: 'tlo.png', exact: true }).click()
    await surface.click({ position: { x: 15, y: 15 } })
    await page.getByRole('button', { name: 'Dopasuj do strony A4' }).click()
    await page.getByLabel('Blokada warstwy 0').click()
    await page.getByRole('button', { name: 'Dodaj warstwę' }).click()
    page.once('dialog', (dialog) => dialog.accept('Teksty i pola'))
    await page.getByRole('button', { name: 'Wybierz warstwę 1', exact: true }).dblclick()
    await page.getByRole('button', { name: 'Przenieś warstwę 0 wyżej', exact: true }).click()
    assert.deepEqual(await page.locator('.creator-layer-select').allTextContents(), ['0', 'Teksty i pola'])
    await page.getByRole('button', { name: 'Przenieś warstwę 0 niżej', exact: true }).click()
    assert.deepEqual(await page.locator('.creator-layer-select').allTextContents(), ['Teksty i pola', '0'])
    await page.getByRole('button', { name: 'Tekst', exact: true }).click()
    await surface.click({ position: { x: 100, y: 100 } })
    await page.getByLabel('Treść', { exact: true }).fill('Zażółć gęślą jaźń')
    await page.getByRole('button', { name: 'Pole', exact: true }).click()
    await page.getByRole('dialog', { name: 'Wybierz pole', exact: true }).getByRole('button', { name: /Aspekt frakcji/ }).click()
    await surface.click({ position: { x: 120, y: 180 } })
    assert.equal(await page.getByLabel('Nazwa pola', { exact: true }).inputValue(), 'Aspekt frakcji')
    await page.getByRole('button', { name: 'Usuń element: Aspekt frakcji', exact: true }).click()
    assert.equal(await page.locator('.creator-element').count(), 2)
    await page.keyboard.press('Control+z')
    assert.equal(await page.locator('.creator-element').count(), 3)
    const draggable = page.locator('.creator-element.field')
    const positionBefore = await draggable.evaluate((element) => [element.style.left, element.style.top])
    const bounds = await draggable.boundingBox()
    await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2)
    await page.mouse.down()
    await page.mouse.move(bounds.x + bounds.width / 2 + 40, bounds.y + bounds.height / 2 + 30, { steps: 8 })
    await page.mouse.up()
    assert.notDeepEqual(await draggable.evaluate((element) => [element.style.left, element.style.top]), positionBefore)
    await page.keyboard.press('Control+z')
    assert.deepEqual(await draggable.evaluate((element) => [element.style.left, element.style.top]), positionBefore)
    page.once('dialog', async (dialog) => {
      assert.equal(dialog.type(), 'prompt')
      await dialog.accept(name)
    })
    await page.keyboard.press('Control+s')
    await page.getByRole('status').filter({ hasText: 'Zapisano projekt.json' }).waitFor()
    created = true
    const project = JSON.parse(await fs.readFile(path.join(directory, 'projekt.json'), 'utf8'))
    assert.equal(project.elements.length, 3)
    assert.equal(project.layers.length, 2)
    assert.equal(project.layers[1].name, 'Teksty i pola')
    assert.equal(project.layers[0].locked, true)
    validateProject(project)
    assert.equal(fieldsConfig(project).fields.length, 1)
    const invalid = structuredClone(project)
    invalid.elements[0].x = -1
    assert.throws(() => validateProject(invalid), /A4/)
    await page.getByRole('button', { name: 'Generuj HTML + PDF + JSON' }).click()
    await page.getByRole('status').filter({ hasText: 'karta.html' }).waitFor({ timeout: 60000 })
    const pdf = await PDFDocument.load(await fs.readFile(path.join(directory, 'karta.pdf')))
    assert.equal(pdf.getPageCount(), 1)
    assert.ok(Math.abs(pdf.getPage(0).getWidth() - PAGE.width) < 1)
    assert.ok(Math.abs(pdf.getPage(0).getHeight() - PAGE.height) < 1)
    const html = await fs.readFile(path.join(directory, 'karta.html'), 'utf8')
    assert.ok(html.includes('Zażółć gęślą jaźń'))
    assert.ok(html.includes('data:image/png;base64,'))
    assert.ok(!html.includes('Aspekt frakcji'))
    const fields = JSON.parse(await fs.readFile(path.join(directory, 'pola.json'), 'utf8'))
    assert.equal(fields.fields[0].label, 'Aspekt frakcji')
    assert.equal(fields.fields[0].id, project.elements[2].id)
    await page.reload()
    await page.getByLabel('Otwórz projekt').selectOption(name)
    await page.waitForFunction(() => document.querySelectorAll('.creator-element').length === 3)
    assert.equal(await page.getByRole('button', { name: 'Wybierz warstwę Teksty i pola', exact: true }).innerText(), 'Teksty i pola')
    await fs.mkdir('/app/.cache', { recursive: true })
    await page.screenshot({ path: '/app/.cache/creator-preview.png', fullPage: true })
    await page.getByLabel('Widoczność warstwy Teksty i pola').click()
    await page.getByRole('button', { name: 'Generuj HTML + PDF + JSON' }).click()
    await page.getByRole('status').filter({ hasText: 'karta.html' }).waitFor({ timeout: 60000 })
    assert.equal(JSON.parse(await fs.readFile(path.join(directory, 'pola.json'), 'utf8')).fields.length, 0)
    assert.ok(!(await fs.readFile(path.join(directory, 'karta.html'), 'utf8')).includes('Zażółć gęślą jaźń'))
    const badPath = await page.request.get('http://localhost:8080/api/card-project?name=..')
    assert.equal(badPath.status(), 400)
    await page.getByRole('button', { name: 'Menu kreatora' }).click()
    await page.getByRole('menuitem', { name: 'Definicja pól', exact: true }).click()
    const definitionsDialog = page.getByRole('dialog', { name: 'Definicja pól', exact: true })
    await definitionsDialog.getByRole('button', { name: 'Dodaj', exact: true }).waitFor()
    assert.equal(await definitionsDialog.getByLabel('Liczba pól', { exact: true }).count(), 0)
    await definitionsDialog.getByRole('button', { name: 'Edytuj Żar', exact: true }).click()
    assert.equal(await definitionsDialog.getByLabel('Liczba pól', { exact: true }).count(), 0)
    await definitionsDialog.getByRole('button', { name: 'Anuluj', exact: true }).click()
    await definitionsDialog.getByRole('button', { name: 'Dodaj', exact: true }).click()
    await definitionsDialog.getByLabel('Typ', { exact: true }).selectOption('text')
    assert.equal(await definitionsDialog.getByLabel('Typ', { exact: true }).locator('option').count(), 2)
    await definitionsDialog.getByRole('button', { name: 'Anuluj', exact: true }).click()
    const libraryResponse = await page.request.get('http://localhost:8080/api/field-definitions')
    assert.equal(libraryResponse.status(), 200)
    const library = await libraryResponse.json()
    assert.ok(library.fields.some((field) => field.id === 'zar' && field.aggregation === 'checkedCount'))
    const invalidLibrary = structuredClone(library)
    invalidLibrary.fields.find((field) => field.id === 'zar').kind = 'invalid'
    const rejected = await page.request.post('http://localhost:8080/api/field-definitions', { data: invalidLibrary })
    assert.equal(rejected.status(), 400)
    assert.deepEqual(await (await page.request.get('http://localhost:8080/api/field-definitions')).json(), library)
    assert.deepEqual(errors, [])
    console.log('Kreator: grafika, tekst PL, pola, warstwy, zapis/odczyt, HTML i jednostronicowy PDF A4 — OK.')
  } finally {
    await browser.close()
    if (created) {
      // Usuwamy wyłącznie cztery pliki utworzone przez ten test, bez rekursji.
      for (const file of ['projekt.json', 'karta.html', 'karta.pdf', 'pola.json']) {
        await fs.unlink(path.join(directory, file)).catch((error) => { if (error.code !== 'ENOENT') throw error })
      }
      await fs.rmdir(directory)
    }
  }
}
verify().catch((error) => { console.error(error); process.exitCode = 1 })
