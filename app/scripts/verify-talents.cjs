const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const express = require('express')
const XLSX = require('xlsx')
const { chromium } = require('playwright-core')
const { installTalents, parseWorkbook, planImport, validateLibrary } = require('./talents-server.cjs')
const { defaultTemplate, renderTemplate } = require('../src/talentTemplates/template.cjs')

const header = ['Nazwa talentu', 'Opis fabularny', 'Opis talentu', 'Ile razy można użyć', 'Kod']
function workbook(rows, type = 'biff8') {
  const book = XLSX.utils.book_new()
  XLSX.utils.book_append_sheet(book, XLSX.utils.aoa_to_sheet([header, ...rows]), 'Talenty')
  return XLSX.write(book, { type: 'buffer', bookType: type, bookSST: true })
}
async function verify() {
  const longDescription = 'Pełny opis z polskimi znakami: żółć, źdźbło. '.repeat(12).trim()
  const original = { id: 'existing', name: 'Talent próbny', flavorDescription: 'Opis fabularny.', description: longDescription, usesPerMission: 3, group: 'Dary Ciemności', subgroup: null, code: 'A7K2-M9B4' }
  const library = { schemaVersion: 1, talents: [original] }
  const formatted = renderTemplate(defaultTemplate(), { ...original, description: '**moc** i *ruch* oraz ***raz***. <script>alert(1)</script> [stan: test] **brak' })
  assert.ok(formatted.includes('<strong>moc</strong>'))
  assert.ok(formatted.includes('<em>ruch</em>'))
  assert.ok(formatted.includes('<strong><em>raz</em></strong>'))
  assert.ok(formatted.includes('&lt;script&gt;'))
  assert.ok(!formatted.includes('<script>'))
  assert.ok(formatted.includes('<span class="talent-state">test</span> **brak'))
  const semantic = renderTemplate(defaultTemplate(), { ...original, description: '[aspekt: [stan: test]] [cecha: **moc**] [stan: <script>x</script>] [aspekt: brak' })
  assert.ok(semantic.includes('<span class="talent-aspect"><span class="talent-state">test</span></span>'))
  assert.ok(semantic.includes('<strong class="talent-trait"><em><strong>moc</strong></em></strong>'))
  assert.ok(!semantic.includes('<script>'))
  assert.ok(semantic.includes('[aspekt: brak'))
  const actionTalent = validateLibrary({ schemaVersion: 1, talents: [{ ...original, name: 'Talent (akcja)' }] }).talents[0]
  assert.equal(actionTalent.name, 'Talent')
  assert.equal(actionTalent.isAction, true)
  assert.equal(validateLibrary(library).talents[0].isAction, false)
  assert.equal(validateLibrary(library).talents[0].oncePerScene, false)
  assert.match(renderTemplate(defaultTemplate(), { ...original, oncePerScene: true }), /data-part="uses">[\s\S]*data-part="oncePerScene"/)
  assert.ok(!renderTemplate(defaultTemplate(), { ...original, oncePerScene: false }).includes('data-part="oncePerScene"'))
  assert.equal(validateLibrary({ ...library, talents: [{ ...original, oncePerScene: true }] }).talents[0].oncePerScene, true)
  assert.throws(() => validateLibrary({ ...library, talents: [{ ...original, oncePerScene: 'tak' }] }), /Raz na scenę/)
  assert.throws(() => validateLibrary({ ...library, talents: [{ ...original, isAction: 'tak' }] }), /akcji/)
  assert.match(renderTemplate(defaultTemplate(), actionTalent), /\(ak(?:\u00ad)?cja\):/)
  assert.ok(!renderTemplate(defaultTemplate(), { ...actionTalent, isAction: false }).includes('(akcja)'))
  const actionLibrary = { schemaVersion: 1, talents: [actionTalent] }
  const oldActionImport = parseWorkbook(workbook([['Talent (akcja)', '', 'Opis.', 1, '']]), original.group, null)
  assert.equal(planImport(actionLibrary, oldActionImport)[0].talent.id, actionTalent.id)
  assert.equal(planImport(actionLibrary, oldActionImport)[0].talent.isAction, true)
  for (const source of ['legacy', 'googledoc']) {
    const sceneLibrary = { ...actionLibrary, talents: [{ ...actionTalent, oncePerScene: true }] }
    assert.equal(planImport(sceneLibrary, oldActionImport, { source })[0].talent.oncePerScene, source !== 'googledoc')
  }
  const fixture = workbook([[original.name, original.flavorDescription, longDescription, 3, '']])
  for (const type of ['biff8', 'xlsx']) {
    const parsed = parseWorkbook(workbook([[original.name, original.flavorDescription, longDescription, 3, '']], type), original.group, null)
    assert.equal(parsed[0].description, longDescription)
    assert.equal(planImport(library, parsed)[0].action, 'unchanged')
    assert.equal(planImport(library, parsed)[0].talent.code, original.code)
    assert.equal(planImport(library, parsed)[0].talent.id, original.id)
  }
  assert.throws(() => parseWorkbook(workbook([['Błędny', '', 'Opis.', '', '']]), original.group, null), /Wiersz 2/)
  assert.throws(() => parseWorkbook(workbook([['Błędny', '', 'Opis.', 4, '']]), original.group, null), /Wiersz 2/)
  assert.throws(() => parseWorkbook(workbook([['Błędny', '', 'Opis.', 1, 'O1I0-ABCD']]), original.group, null), /kod/)
  assert.throws(() => parseWorkbook(Buffer.from('<html>'), original.group, null), /XLS/)
  assert.throws(() => validateLibrary({ schemaVersion: 1, talents: [original, { ...original, id: 'other' }] }), /Powtórzone/)
  const changed = { ...original, description: 'Poprawiony opis.', code: null }
  assert.equal(planImport(library, [changed])[0].action, 'update')
  assert.throws(() => planImport(library, [{ ...changed, code: 'BBBB-CCCC' }]), /zmienić/)
  assert.throws(() => planImport(library, [changed, changed]), /Powtórzony/)
  const formulaBook = XLSX.utils.book_new()
  const formulaSheet = XLSX.utils.aoa_to_sheet([header, ['Błędny', '', 'Opis.', 1, '']])
  formulaSheet.A2 = { t: 's', v: 'Błędny', f: 'CONCAT("A","B")' }
  XLSX.utils.book_append_sheet(formulaBook, formulaSheet, 'Talenty')
  assert.throws(() => parseWorkbook(XLSX.write(formulaBook, { type: 'buffer', bookType: 'xlsx' }), original.group, null), /formułę/)

  // Test saves and imports against an isolated file, never the user's live library.
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'klanarchia-talents-'))
  const file = path.join(directory, 'talenty.json')
  fs.writeFileSync(file, JSON.stringify(library))
  const app = express()
  installTalents(app, file)
  const server = await new Promise((resolve) => { const instance = app.listen(0, '127.0.0.1', () => resolve(instance)) })
  const base = `http://127.0.0.1:${server.address().port}`
  let browser
  const post = (url, data) => fetch(base + url, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(data) })
  try {
    const initial = await (await fetch(base + '/api/talents')).json()
    const bad = await post('/api/talents/save', { revision: initial.revision, talent: { ...original, code: null } })
    assert.equal(bad.status, 400)
    const savedResponse = await post('/api/talents/save', { revision: initial.revision, talent: { ...original, description: 'Zapis przez API.' } })
    assert.equal(savedResponse.status, 200)
    const stale = await post('/api/talents/save', { revision: initial.revision, talent: original })
    assert.equal(stale.status, 409)
    assert.ok(fs.existsSync(file + '.bak'))
    const beforePreview = fs.readFileSync(file, 'utf8')
    const previewResponse = await fetch(base + '/api/talents/import-preview?group=Dary%20Ciemno%C5%9Bci', { method: 'POST', body: fixture })
    assert.equal(previewResponse.status, 200)
    assert.equal(fs.readFileSync(file, 'utf8'), beforePreview)

    browser = await chromium.launch({ executablePath: '/usr/bin/chromium', args: ['--no-sandbox', '--disable-dev-shm-usage'] })
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
    const errors = []
    page.on('pageerror', (error) => errors.push(error.message))
    await page.route('**/api/talents**', async (route) => {
      const url = new URL(route.request().url())
      const response = await route.fetch({ url: base + url.pathname + url.search })
      await route.fulfill({ response })
    })
    await page.goto('http://localhost:8080/#dev-talents')
    await page.getByLabel('Nazwa talentu', { exact: true }).waitFor()
    assert.equal(await page.getByLabel('Nazwa talentu', { exact: true }).inputValue(), original.name)
    const descriptionInput = page.getByLabel(/^Opis talentu/)
    await descriptionInput.fill('**Moc** i *ruch*.\n[cecha: Siła] [aspekt: [stan: Gniew]] ***raz***.')
    await descriptionInput.evaluate((input) => input.setSelectionRange(0, 3))
    await page.getByRole('button', { name: 'Usuń formatowanie', exact: true }).click()
    assert.equal(await descriptionInput.inputValue(), 'Moc i ruch.\nSiła Gniew raz.')
    for (const [label, open, close] of [['Pogrubienie', '**', '**'], ['Kursywa', '*', '*'], ['Cecha', '[cecha: ', ']'], ['Aspekt', '[aspekt: ', ']'], ['Stan', '[stan: ', ']']]) {
      await descriptionInput.fill('Przed wyraz po.')
      await descriptionInput.evaluate((input) => { input.focus(); input.setSelectionRange(6, 11) })
      await page.getByRole('button', { name: label, exact: true }).click()
      assert.equal(await descriptionInput.inputValue(), `Przed ${open}wyraz${close} po.`)
      if (label === 'Pogrubienie' || label === 'Kursywa') {
        const tag = label === 'Pogrubienie' ? 'strong' : 'em'
        await page.frameLocator('iframe[title="Karta wybranego talentu"]').locator(`[data-part="description"] ${tag}`).waitFor()
      }
      await page.waitForFunction(({ start, end }) => {
        const input = document.querySelector('.talent-editor textarea[required]')
        return document.activeElement === input && input.selectionStart === start && input.selectionEnd === end
      }, { start: 6 + open.length, end: 11 + open.length })
    }
    await descriptionInput.fill('Przed wyraz po.')
    await descriptionInput.evaluate((input) => { input.focus(); input.setSelectionRange(6, 6) })
    await page.getByRole('button', { name: 'Cecha', exact: true }).click()
    assert.equal(await descriptionInput.inputValue(), 'Przed [cecha: ]wyraz po.')
    await page.getByLabel(/^Opis talentu/).fill('Treść poprawiona w przeglądarce: żółć.')
    await page.getByRole('checkbox', { name: 'isAction — Akcja', exact: true }).check()
    await page.waitForFunction(() => document.querySelector('iframe[title="Karta wybranego talentu"]')?.contentDocument?.querySelector('[data-part="name"]')?.textContent.replace(/\u00ad/g, '').includes('(akcja):'))
    await page.waitForFunction(() => {
      const doc = document.querySelector('iframe[title="Karta wybranego talentu"]')?.contentDocument
      return doc?.querySelector('[data-part="description"]')?.textContent.replace(/\u00ad/g, '').replace(/\u00a0/g, ' ') === 'Treść poprawiona w przeglądarce: żółć.'
    })
    assert.equal(JSON.parse(fs.readFileSync(file)).talents[0].description, 'Zapis przez API.')
    const card = page.frameLocator('iframe[title="Karta wybranego talentu"]')
    assert.equal(await card.locator('[contenteditable]').count(), 0)
    assert.equal(await card.getByRole('textbox').count(), 0)
    await page.getByRole('button', { name: 'Zapisz talent', exact: true }).click()
    await page.getByRole('status').filter({ hasText: 'Zapisano talent.' }).waitFor()
    await page.reload()
    await page.getByLabel('Nazwa talentu', { exact: true }).waitFor()
    assert.equal(await page.getByLabel(/^Opis talentu/).inputValue(), 'Treść poprawiona w przeglądarce: żółć.')
    const incoming = workbook([[original.name, '', 'Nowy opis z arkusza.', 2, ''], ['Nowy talent', '', longDescription, 0, '']])
    await page.getByRole('button', { name: 'Importuj XLS / XLSX' }).click()
    await page.getByLabel('Plik XLS lub XLSX').setInputFiles({ name: 'talenty.xls', mimeType: 'application/vnd.ms-excel', buffer: incoming })
    await page.getByRole('button', { name: 'Pokaż podgląd importu' }).click()
    await page.getByRole('heading', { name: 'Podgląd importu', exact: true }).waitFor()
    assert.equal(JSON.parse(fs.readFileSync(file)).talents.length, 1)
    await page.getByRole('button', { name: 'Zatwierdź import' }).click()
    await page.getByRole('status').filter({ hasText: 'Import zakończony' }).waitFor()
    const after = JSON.parse(fs.readFileSync(file))
    assert.equal(after.talents.length, 2)
    assert.equal(after.talents[0].id, original.id)
    assert.equal(after.talents[0].code, original.code)
    assert.equal(after.talents[0].description, 'Nowy opis z arkusza.')
    assert.equal(after.talents[0].isAction, true)
    assert.equal(await card.locator('[data-part="flavor"]').count(), 0)
    assert.equal(await card.locator('[data-placeholder]').count(), 0)
    await page.getByLabel(/^Opis fabularny/).fill('Opis dodany w edytorze.')
    await card.locator('[data-part="flavor"]').waitFor()
    assert.equal(await card.locator('[data-part="flavor"]').textContent().then((text) => text.replace(/\u00ad/g, '').replace(/\u00a0/g, ' ')), 'Opis dodany w edytorze.')
    page.once('dialog', (dialog) => dialog.accept())
    await page.getByRole('button', { name: 'Odrzuć zmiany' }).click()
    assert.equal(await page.getByLabel(/^Opis fabularny/).inputValue(), '')
    assert.equal(after.talents[1].description, longDescription)
    await page.getByLabel('Szukaj talentu').fill('Nowy talent')
    assert.equal(await page.locator('.talent-list button').count(), 1)
    await page.getByLabel('Szukaj talentu').fill('nieistniejący')
    await page.getByText('Brak pasujących talentów.', { exact: true }).waitFor()
    await page.getByLabel('Szukaj talentu').fill('')
    await page.locator('.talent-filters select').nth(0).selectOption('Dary Ciemności')
    await page.locator('.talent-filters select').nth(1).selectOption('__none')
    assert.equal(await page.locator('.talent-list button').count(), 2)
    await page.getByLabel('Nazwa talentu', { exact: true }).fill('Niezapisany')
    page.once('dialog', (dialog) => dialog.dismiss())
    await page.locator('.talent-filters select').nth(1).selectOption('')
    assert.equal(await page.locator('.talent-filters select').nth(1).inputValue(), '__none')
    assert.equal(await page.getByLabel('Nazwa talentu', { exact: true }).inputValue(), 'Niezapisany')
    page.once('dialog', (dialog) => dialog.dismiss())
    await page.locator('.talent-filters select').nth(0).selectOption('')
    assert.equal(await page.locator('.talent-filters select').nth(0).inputValue(), 'Dary Ciemności')
    page.once('dialog', (dialog) => dialog.accept())
    await page.locator('.talent-filters select').nth(1).selectOption('')
    assert.equal(await page.locator('.talent-filters select').nth(1).inputValue(), '')
    assert.equal(await page.getByLabel('Nazwa talentu', { exact: true }).inputValue(), original.name)
    assert.equal(await page.getByRole('button', { name: 'Zapisz talent', exact: true }).isDisabled(), true)
    await page.getByLabel('Nazwa talentu', { exact: true }).fill('Niezapisany')
    page.once('dialog', (dialog) => dialog.dismiss())
    await page.getByRole('button', { name: 'Nowy talent Dary Ciemności', exact: true }).click()
    assert.equal(await page.getByLabel('Nazwa talentu', { exact: true }).inputValue(), 'Niezapisany')
    page.once('dialog', (dialog) => dialog.accept())
    await page.getByRole('button', { name: 'Odrzuć zmiany' }).click()
    await page.setViewportSize({ width: 390, height: 844 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true)
    await page.screenshot({ path: '/app/.cache/talents-mobile.png', fullPage: true })
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.screenshot({ path: '/app/.cache/talents-desktop.png', fullPage: true })
    const beforeCreate = fs.readFileSync(file, 'utf8')
    await page.getByRole('button', { name: 'Nowy talent', exact: true }).click()
    assert.equal(await page.getByLabel('Nazwa talentu', { exact: true }).inputValue(), '')
    assert.equal(fs.readFileSync(file, 'utf8'), beforeCreate)
    assert.equal(await page.getByRole('checkbox', { name: 'Raz na scenę', exact: true }).isChecked(), false)
    await page.getByLabel('Nazwa talentu', { exact: true }).fill('Ręcznie utworzony test')
    await descriptionInput.fill('Opis testowy.')
    await page.getByRole('button', { name: 'Zapisz talent', exact: true }).click()
    await page.getByRole('status').filter({ hasText: 'Zapisano talent.' }).waitFor()
    const afterCreate = JSON.parse(fs.readFileSync(file, 'utf8'))
    const created = afterCreate.talents.find((t) => t.name === 'Ręcznie utworzony test')
    assert.ok(created)
    assert.match(created.id, /^[a-f0-9-]{36}$/)
    assert.equal(created.code, null)
    assert.equal(created.oncePerScene, false)
    const currentRevision = (await (await fetch(base + '/api/talents')).json()).revision
    assert.equal((await post('/api/talents/create', { revision: currentRevision, talent: created })).status, 400)
    assert.equal((await post('/api/talents/create', { revision: initial.revision, talent: { ...created, name: 'Nieaktualna rewizja' } })).status, 409)
    assert.equal(JSON.parse(fs.readFileSync(file, 'utf8')).talents.length, afterCreate.talents.length)
    assert.deepEqual(errors, [])
    console.log('OK: XLS/XLSX, pełne opisy, walidacja, zachowanie ID i kodów, konflikt zapisu, podgląd bez zapisu, import i edycja w przeglądarce, filtry, ochrona niezapisanych zmian, ekran mobilny.')
  } finally {
    if (browser) await browser.close()
    await new Promise((resolve) => server.close(resolve))
    fs.rmSync(directory, { recursive: true, force: true })
  }
}
verify().catch((error) => { console.error(error); process.exitCode = 1 })
