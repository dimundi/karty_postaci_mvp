const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const express = require('express')
const XLSX = require('xlsx')
const { chromium } = require('playwright-core')
const { installTalents, parseWorkbook, planImport, validateLibrary } = require('./talents-server.cjs')

const header = ['Nazwa talentu', 'Opis fabularny', 'Opis talentu', 'Ile razy można użyć', 'Kod']
function workbook(rows, type = 'biff8') {
  const book = XLSX.utils.book_new()
  XLSX.utils.book_append_sheet(book, XLSX.utils.aoa_to_sheet([header, ...rows]), 'Talenty')
  return XLSX.write(book, { type: 'buffer', bookType: type, bookSST: true })
}
async function verify() {
  const longDescription = 'Pełny opis z polskimi znakami: żółć, źdźbło. '.repeat(12).trim()
  const original = { id: 'existing', name: 'Talent próbny', flavorDescription: 'Opis fabularny.', description: longDescription, usesPerMission: 3, group: 'Dary Ciemności', subgroup: null, code: 'A7K2-M9B4' }
  const library = { schemaVersion: 1, talents: [original] }
  const fixture = workbook([[original.name, original.flavorDescription, longDescription, 3, '']])
  for (const type of ['biff8', 'xlsx']) {
    const parsed = parseWorkbook(workbook([[original.name, original.flavorDescription, longDescription, 3, '']], type), original.group, null)
    assert.equal(parsed[0].description, longDescription)
    assert.equal(planImport(library, parsed)[0].action, 'unchanged')
    assert.equal(planImport(library, parsed)[0].talent.code, original.code)
    assert.equal(planImport(library, parsed)[0].talent.id, original.id)
  }
  assert.throws(() => parseWorkbook(workbook([['Błędny', '', 'Opis.', '', '']]), original.group, null), /Wiersz 2/)
  assert.throws(() => parseWorkbook(workbook([['Błędny', '', 'Opis.', 4, '']]), original.group, null), /Wiersz 2/)
  assert.throws(() => parseWorkbook(workbook([['Błędny', '', 'Opis.', 1, 'O1I0-ABCD']]), original.group, null), /kod/)
  assert.throws(() => parseWorkbook(Buffer.from('<html>'), original.group, null), /XLS/)
  assert.throws(() => validateLibrary({ schemaVersion: 1, talents: [original, { ...original, id: 'other' }] }), /Powtórzone/)
  const changed = { ...original, description: 'Poprawiony opis.', code: null }
  assert.equal(planImport(library, [changed])[0].action, 'update')
  assert.throws(() => planImport(library, [{ ...changed, code: 'BBBB-CCCC' }]), /zmienić/)
  assert.throws(() => planImport(library, [changed, changed]), /Powtórzony/)
  const formulaBook = XLSX.utils.book_new()
  const formulaSheet = XLSX.utils.aoa_to_sheet([header, ['Błędny', '', 'Opis.', 1, '']])
  formulaSheet.A2 = { t: 's', v: 'Błędny', f: 'CONCAT("A","B")' }
  XLSX.utils.book_append_sheet(formulaBook, formulaSheet, 'Talenty')
  assert.throws(() => parseWorkbook(XLSX.write(formulaBook, { type: 'buffer', bookType: 'xlsx' }), original.group, null), /formułę/)

  // Test saves and imports against an isolated file, never the user's live library.
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'klanarchia-talents-'))
  const file = path.join(directory, 'talenty.json')
  fs.writeFileSync(file, JSON.stringify(library))
  const app = express()
  installTalents(app, file)
  const server = await new Promise((resolve) => { const instance = app.listen(0, '127.0.0.1', () => resolve(instance)) })
  const base = `http://127.0.0.1:${server.address().port}`
  let browser
  const post = (url, data) => fetch(base + url, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(data) })
  try {
    const initial = await (await fetch(base + '/api/talents')).json()
    const bad = await post('/api/talents/save', { revision: initial.revision, talent: { ...original, code: null } })
    assert.equal(bad.status, 400)
    const savedResponse = await post('/api/talents/save', { revision: initial.revision, talent: { ...original, description: 'Zapis przez API.' } })
    assert.equal(savedResponse.status, 200)
    const stale = await post('/api/talents/save', { revision: initial.revision, talent: original })
    assert.equal(stale.status, 409)
    assert.ok(fs.existsSync(file + '.bak'))
    const beforePreview = fs.readFileSync(file, 'utf8')
    const previewResponse = await fetch(base + '/api/talents/import-preview?group=Dary%20Ciemno%C5%9Bci', { method: 'POST', body: fixture })
    assert.equal(previewResponse.status, 200)
    assert.equal(fs.readFileSync(file, 'utf8'), beforePreview)

    browser = await chromium.launch({ executablePath: '/usr/bin/chromium', args: ['--no-sandbox', '--disable-dev-shm-usage'] })
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
    const errors = []
    page.on('pageerror', (error) => errors.push(error.message))
    await page.route('**/api/talents**', async (route) => {
      const url = new URL(route.request().url())
      const response = await route.fetch({ url: base + url.pathname + url.search })
      await route.fulfill({ response })
    })
    await page.goto('http://localhost:8080/#dev-talents')
    await page.getByLabel('Nazwa talentu', { exact: true }).waitFor()
    assert.equal(await page.getByLabel('Nazwa talentu', { exact: true }).inputValue(), original.name)
    await page.getByLabel('Opis talentu', { exact: true }).fill('Treść poprawiona w przeglądarce: żółć.')
    await page.getByRole('button', { name: 'Zapisz talent', exact: true }).click()
    await page.getByRole('status').filter({ hasText: 'Zapisano talent.' }).waitFor()
    await page.reload()
    await page.getByLabel('Nazwa talentu', { exact: true }).waitFor()
    assert.equal(await page.getByLabel('Opis talentu', { exact: true }).inputValue(), 'Treść poprawiona w przeglądarce: żółć.')
    const incoming = workbook([[original.name, '', 'Nowy opis z arkusza.', 2, ''], ['Nowy talent', '', longDescription, 0, '']])
    await page.getByRole('button', { name: 'Importuj XLS / XLSX' }).click()
    await page.getByLabel('Plik XLS lub XLSX').setInputFiles({ name: 'talenty.xls', mimeType: 'application/vnd.ms-excel', buffer: incoming })
    await page.getByRole('button', { name: 'Pokaż podgląd importu' }).click()
    await page.getByRole('heading', { name: 'Podgląd importu', exact: true }).waitFor()
    assert.equal(JSON.parse(fs.readFileSync(file)).talents.length, 1)
    await page.getByRole('button', { name: 'Zatwierdź import' }).click()
    await page.getByRole('status').filter({ hasText: 'Import zakończony' }).waitFor()
    const after = JSON.parse(fs.readFileSync(file))
    assert.equal(after.talents.length, 2)
    assert.equal(after.talents[0].id, original.id)
    assert.equal(after.talents[0].code, original.code)
    assert.equal(after.talents[0].description, 'Nowy opis z arkusza.')
    assert.equal(after.talents[1].description, longDescription)
    await page.getByLabel('Szukaj talentu').fill('Nowy talent')
    assert.equal(await page.locator('.talent-list button').count(), 1)
    await page.getByLabel('Szukaj talentu').fill('nieistniejący')
    await page.getByText('Brak pasujących talentów.', { exact: true }).waitFor()
    await page.getByLabel('Szukaj talentu').fill('')
    await page.getByLabel('Grupa', { exact: true }).first().selectOption('Dary Ciemności')
    await page.getByLabel('Podgrupa', { exact: true }).selectOption('__none')
    assert.equal(await page.locator('.talent-list button').count(), 2)
    await page.getByLabel('Nazwa talentu', { exact: true }).fill('Niezapisany')
    page.once('dialog', (dialog) => dialog.dismiss())
    await page.getByRole('button', { name: 'Nowy talent Dary Ciemności', exact: true }).click()
    assert.equal(await page.getByLabel('Nazwa talentu', { exact: true }).inputValue(), 'Niezapisany')
    page.once('dialog', (dialog) => dialog.accept())
    await page.getByRole('button', { name: 'Odrzuć zmiany' }).click()
    await page.setViewportSize({ width: 390, height: 844 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true)
    await page.screenshot({ path: '/app/.cache/talents-mobile.png', fullPage: true })
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.screenshot({ path: '/app/.cache/talents-desktop.png', fullPage: true })
    assert.deepEqual(errors, [])
    console.log('OK: XLS/XLSX, pełne opisy, walidacja, zachowanie ID i kodów, konflikt zapisu, podgląd bez zapisu, import i edycja w przeglądarce, filtry, ochrona niezapisanych zmian, ekran mobilny.')
  } finally {
    if (browser) await browser.close()
    await new Promise((resolve) => server.close(resolve))
    fs.rmSync(directory, { recursive: true, force: true })
  }
}
verify().catch((error) => { console.error(error); process.exitCode = 1 })
