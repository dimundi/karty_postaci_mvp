const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const os = require('node:os')
const { execFileSync } = require('node:child_process')
const express = require('express')
const { chromium } = require('playwright-core')
const { installMailingList, normalizeEmail } = require('./mailing-list-server.cjs')

async function verify() {
  execFileSync(process.execPath, ['node_modules/typescript/bin/tsc', '--noEmit'], { stdio: 'inherit' })
  assert.equal(normalizeEmail('  Test+tag@Example.COM  '), 'test+tag@example.com')
  for (const invalid of ['', 'not-an-email', 'a@@example.com', 'a@example', '.a@example.com', 'a..b@example.com', 'a@-bad.example', 'a@bad..example', 'a@example.com\nbcc:x@example.com']) assert.throws(() => normalizeEmail(invalid))
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'klanarchia-mailing-'))
  const file = path.join(directory, 'mailing-list.json')
  const app = express(); installMailingList(app, file)
  const server = await new Promise((resolve) => { const s = app.listen(0, '127.0.0.1', () => resolve(s)); })
  const base = `http://127.0.0.1:${server.address().port}`
  const add = (email) => fetch(base + '/api/mailing-list', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ email }) })
  let browser, page
  try {
    const initial = await fetch(base + '/api/mailing-list')
    assert.equal(initial.headers.get('cache-control'), 'no-store')
    assert.deepEqual((await initial.json()).recipients, [])
    assert.equal((await add('invalid')).status, 400)
    assert.equal(fs.existsSync(file), false)
    assert.equal((await add('Test@Example.com')).status, 200)
    assert.equal((await add('test@example.COM')).status, 409)
    const results = await Promise.all([add('second@example.com'), add('third@example.com')])
    assert.ok(results.every((r) => r.status === 200))
    const contacts = JSON.parse(fs.readFileSync(file))
    assert.equal(contacts.recipients.length, 3)
    assert.equal(new Set(contacts.recipients.map((e) => e.id)).size, 3)
    assert.ok(fs.existsSync(file + '.bak'))
    contacts.recipients[0].deliveryStatus = 'sent'
    contacts.recipients[0].talentId = 'talent-test-001'
    fs.writeFileSync(file, JSON.stringify(contacts))
    const send = (recipientId) => fetch(base + '/api/mailing-list/send', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ recipientId }) })
    assert.equal((await send(contacts.recipients[0].id)).status, 409)
    assert.equal((await send('not-found')).status, 404)
    browser = await chromium.launch({ executablePath: '/usr/bin/chromium', args: ['--no-sandbox', '--disable-dev-shm-usage'] })
    page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
    const errors = []; page.on('pageerror', (e) => errors.push(e.message))
    await page.route('**/api/mailing-list**', async (route) => { const url = new URL(route.request().url()); const response = await route.fetch({ url: base + url.pathname }); await route.fulfill({ response }) })
    await page.goto('http://localhost:8080/#dev')
    await page.getByRole('link', { name: /Lista mailingowa/ }).click()
    await page.getByRole('cell', { name: 'test@example.com', exact: true }).waitFor()
    await page.getByRole('cell', { name: 'talent-test-001', exact: true }).waitFor()
    assert.equal(await page.getByRole('button', { name: 'Wyślij do test@example.com', exact: true }).isDisabled(), true)
    assert.equal(await page.getByRole('button', { name: 'Przeglądaj', exact: true }).isEnabled(), true)
    await page.getByLabel('Adres e-mail', { exact: true }).fill('NEW@Example.com')
    await page.getByRole('button', { name: 'Dodaj adres', exact: true }).click()
    await page.getByRole('status').filter({ hasText: 'Dodano adres' }).waitFor()
    await page.getByRole('cell', { name: 'new@example.com', exact: true }).waitFor()
    await page.reload()
    await page.getByRole('cell', { name: 'new@example.com', exact: true }).waitFor()
    await page.getByLabel('Adres e-mail', { exact: true }).fill('NEW@example.com')
    await page.getByRole('button', { name: 'Dodaj adres', exact: true }).click()
    await page.getByRole('alert').filter({ hasText: 'już na liście' }).waitFor()
    assert.equal(JSON.parse(fs.readFileSync(file)).recipients.length, 4)
    const beforeSend = fs.readFileSync(file, 'utf8')
    await page.getByRole('button', { name: 'Wyślij do new@example.com', exact: true }).click()
    await page.getByRole('heading', { name: 'Podgląd wysyłki', exact: true }).waitFor()
    assert.equal(await page.getByRole('heading', { name: 'Zapisane adresy', exact: true }).isVisible(), false)
    await page.setViewportSize({ width: 390, height: 300 })
    const scroller = page.locator('main.mailing-list')
    await scroller.hover({ position: { x: 10, y: 200 } })
    await page.mouse.wheel(0, 500)
    await page.waitForFunction(() => document.querySelector('main.mailing-list').scrollTop > 0)
    await scroller.evaluate((el) => { el.scrollTop = 0 })
    await page.getByRole('button', { name: '← Wróć do listy', exact: true }).click()
    await page.getByRole('heading', { name: 'Zapisane adresy', exact: true }).waitFor()
    assert.equal(await page.getByRole('button', { name: 'Wyślij do new@example.com', exact: true }).evaluate((el) => el === document.activeElement), true)
    await page.setViewportSize({ width: 1440, height: 1000 })
    assert.equal(fs.readFileSync(file, 'utf8'), beforeSend)
    assert.equal(JSON.parse(beforeSend).recipients.find((entry) => entry.email === 'new@example.com').talentId, null)
    await page.getByLabel('Szukaj adresu', { exact: true }).fill('SECOND')
    assert.equal(await page.locator('tbody tr').count(), 1)
    await page.getByLabel('Szukaj adresu', { exact: true }).fill('not-found')
    await page.getByText('Brak pasujących adresów.', { exact: true }).waitFor()
    await page.getByLabel('Szukaj adresu', { exact: true }).fill('')
    await page.setViewportSize({ width: 390, height: 844 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true)
    await page.screenshot({ path: '/app/.cache/mailing-list-mobile.png', fullPage: true })
    assert.deepEqual(errors, [])
    fs.writeFileSync(file, 'broken-json')
    assert.equal((await add('fourth@example.com')).status, 500)
    assert.equal(fs.readFileSync(file, 'utf8'), 'broken-json')
    console.log('OK: TypeScript; walidacja, duplikaty niezależne od wielkości liter, równoczesne dodawanie, trwały zapis i kopia, formularz, odświeżenie, wyszukiwanie, przycisk wyboru pliku, ekran mobilny i ochrona uszkodzonego JSON-a. Wyłącznie dane testowe.')
  } catch (error) { if (page) await page.screenshot({ path: '/app/.cache/mailing-list-error.png', fullPage: true }).catch(() => {}); throw error }
  finally { if (browser) await browser.close(); await new Promise((resolve) => server.close(resolve)); fs.rmSync(directory, { recursive: true, force: true }) }
}
verify().catch((error) => { console.error(error); process.exitCode = 1 })
